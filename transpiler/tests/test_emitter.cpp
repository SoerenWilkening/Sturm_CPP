// test_emitter.cpp — unit tests for the M9 C++ emitter.
//
// The emitter is the last module in the transpiler pipeline:
//
//   M7 matcher  →  M8 synthesize  →  M9 emit  →  file on disk
//
// These tests exercise three layers:
//
//   1. Pure helpers — idempotency_header() and should_skip() are string-only
//      functions with no LibTooling dependency. They are checked directly
//      to lock in the canonical header format and the skip-detection rules.
//
//   2. Golden snapshot — drive the full emit() call on the PRD's MVP input
//      using a real Clang SourceManager + Rewriter produced via LibTooling.
//      Compare the generated bytes against the locked canonical form so any
//      regression in the emitter's whitespace or header pops up immediately.
//
//   3. Idempotency — take the emitter's output, feed it back through the
//      pipeline's skip-detection layer, and confirm the file is treated as
//      pass-through. This is PRD AC #5 checked at the unit level.
//
// The tests assemble a tiny qbool stub inline so no external STURM include
// path is required. All SourceManager traffic happens inside
// `runToolOnCodeWithArgs`, matching the test_matcher.cpp pattern.

