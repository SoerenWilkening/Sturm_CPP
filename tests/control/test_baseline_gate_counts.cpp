// ── Artifact writer ────────────────────────────────────────────────────────
// Writes the captured numbers into a small text file the orchestrator can
// commit alongside the test source.  The path is the test's first argv
// entry when present, otherwise `baseline_gate_counts.txt` in the cwd of
// the running test (CTest sets cwd to the binary directory of the test
// target by default).
struct Row {
    const char* op;
    std::size_t n;
    uint64_t    bare;
    uint64_t    when;
    bool        skipped;
    const char* skip_reason;
};

int main(int argc, char** argv) {
    std::printf("sturm-a3t4.1 P0 baseline gate counts (depth-1 refactor):\n");

    std::vector<Row> rows;

    // n = 8 -- all three primitives.
    rows.push_back({"lib_add_mod_dsl", 8u,
                    measure_add_mod(8u, /*when=*/false),
                    measure_add_mod(8u, /*when=*/true),
                    false, ""});
    rows.push_back({"lib_mul_mod_dsl", 8u,
                    measure_mul_mod(8u, /*when=*/false),
                    measure_mul_mod(8u, /*when=*/true),
                    false, ""});
    rows.push_back({"lib_pow_mod_dsl", 8u,
                    measure_pow_mod(8u, /*when=*/false),
                    measure_pow_mod(8u, /*when=*/true),
                    false, ""});

    // n = 16 -- only add_mod (mul_mod / pow_mod cap at kMaxN=8).
    rows.push_back({"lib_add_mod_dsl", 16u,
                    measure_add_mod(16u, /*when=*/false),
                    measure_add_mod(16u, /*when=*/true),
                    false, ""});
    rows.push_back({"lib_mul_mod_dsl", 16u, 0u, 0u,
                    true, "kMaxN=8 in mul_mod_dsl.hpp"});
    rows.push_back({"lib_pow_mod_dsl", 16u, 0u, 0u,
                    true, "kMaxN=8 in pow_mod_dsl.hpp"});

    // ── Print human-readable table ─────────────────────────────────────────
    std::printf("%-18s  %4s  %14s  %14s\n",
                "primitive", "n", "bare_gates", "when_gates");
    std::printf("%-18s  %4s  %14s  %14s\n",
                "---------", "-", "----------", "----------");
    for (const Row& r : rows) {
        if (r.skipped) {
            std::printf("%-18s  %4zu  %14s  %14s   # %s\n",
                        r.op, r.n, "N/A", "N/A", r.skip_reason);
        } else {
            std::printf("%-18s  %4zu  %14llu  %14llu\n",
                        r.op, r.n,
                        static_cast<unsigned long long>(r.bare),
                        static_cast<unsigned long long>(r.when));
        }
    }

    // ── Write the artifact ─────────────────────────────────────────────────
    // Plain text, two-column "primitive,n,bare,when" format that grep/diff
    // can pick up without a parser.
    const char* out_path = (argc > 1) ? argv[1] : "baseline_gate_counts.txt";
    std::FILE* fp = std::fopen(out_path, "w");
    if (!fp) {
        std::fprintf(stderr, "warning: could not open %s for writing\n",
                     out_path);
    } else {
        std::fprintf(fp, "# sturm-a3t4.1 P0 baseline gate counts.\n");
        std::fprintf(fp, "# Captured by tests/control/test_baseline_gate_counts.cpp.\n");
        std::fprintf(fp, "# Format: <primitive> <n> <bare_gates> <when_gates>\n");
        std::fprintf(fp, "# bare_gates  : sturm_gate_count delta with no enclosing WHEN.\n");
        std::fprintf(fp, "# when_gates  : sturm_gate_count delta inside a single WHEN(c).\n");
        std::fprintf(fp, "# 'N/A' rows  : primitive's kMaxN cap forbids that width.\n");
        for (const Row& r : rows) {
            if (r.skipped) {
                std::fprintf(fp, "%s %zu N/A N/A # %s\n",
                             r.op, r.n, r.skip_reason);
            } else {
                std::fprintf(fp, "%s %zu %llu %llu\n",
                             r.op, r.n,
                             static_cast<unsigned long long>(r.bare),
                             static_cast<unsigned long long>(r.when));
            }
        }
        std::fclose(fp);
        std::printf("wrote artifact: %s\n", out_path);
    }

    // ── Smoke assertions ───────────────────────────────────────────────────
    // The numerical baseline is captured in the artifact above; this test
    // additionally pins three structural invariants that the refactor must
    // not break:
    //   1. every measured row emits at least one gate (we are measuring a
    //      non-empty primitive);
    //   2. wrapping in WHEN(c) never DECREASES the gate count vs. bare
    //      (an extra control flag should at minimum do as much work as
    //      bare, since the lift pattern preserves operation count);
    //   3. add_mod n=16 emits more gates than add_mod n=8 (sanity that
    //      the width parameter is actually flowing through).
    for (const Row& r : rows) {
        if (r.skipped) continue;
        assert(r.bare > 0 && "bare gate count must be non-zero");
        assert(r.when > 0 && "WHEN gate count must be non-zero");
        assert(r.when >= r.bare
               && "WHEN(c) wrapper should not reduce gate count");
    }
    {
        uint64_t add_n8  = 0, add_n16 = 0;
        for (const Row& r : rows) {
            if (std::strcmp(r.op, "lib_add_mod_dsl") == 0) {
                if (r.n == 8u)  add_n8  = r.bare;
                if (r.n == 16u) add_n16 = r.bare;
            }
        }
        assert(add_n8  > 0 && "add_mod n=8 baseline must be measured");
        assert(add_n16 > 0 && "add_mod n=16 baseline must be measured");
        assert(add_n16 > add_n8
               && "add_mod gate count must scale up with width");
    }

    std::printf("All sturm-a3t4.1 baseline checks passed.\n");
    return 0;
}
