// test_baseline_gate_counts.cpp -- sturm-a3t4.1 P0
//
// Captures a gate-count baseline for `lib_add_mod_dsl`,
// `lib_mul_mod_dsl`, and `lib_pow_mod_dsl` at register widths n=8 and
// n=16, both bare (no enclosing WHEN) and inside a single `WHEN(c)`
// scope where `c` is a one-qubit superposed control.  The numbers
// captured here are the pre-refactor reference point for the
// sturm-a3t4 epic ("depth-1 control stack invariant"); after the
// refactor lands, this file is re-run and the deltas relative to the
// committed baseline at `tests/control/baseline_gate_counts.txt` show
// whether the depth-1 lift pattern actually reduced the gate cost.
//
// Method (issue body):
//   - Run each primitive in `STURM_MODE_COUNT_ONLY` mode with the
//     minimal harness needed (allocate the input/output registers from
//     `QubitPool`, mark every owner as superposed so classicality
//     specialisation doesn't short-circuit the dispatch, install a
//     fresh `BackendContext`, and bracket the call with
//     `sturm_gate_count` reads).
//   - For the WHEN(c) variant, wrap the call in a `WHEN(c)` whose
//     control qbool is a freshly-allocated superposed flag (the same
//     pattern used by `tests/transpiler/test_gate_equivalence.cpp` for
//     control-stack tests).
//
// Coverage caveats:
//   - `lib_mul_mod_dsl` and `lib_pow_mod_dsl` cap their internal arrays
//     at `kMaxN = 8` (see the assert at the head of each header), so
//     the n=16 row of the baseline only applies to `lib_add_mod_dsl`
//     (whose `kMaxN = 32`).  The mul_mod / pow_mod n=16 cells of the
//     baseline file are written as `N/A (kMaxN=8)` so the artifact
//     still has a complete row layout.
//   - At n=8 `lib_pow_mod_dsl` peaks at 4·W² + 2W + 8 = 280 transient
//     ancillas above the 4·W=32 input qubits — beyond the default
//     STURM_ANCILLA_CAPACITY=256.  The test target compiles with
//     STURM_ANCILLA_CAPACITY=512 so the pow_mod n=8 cell can be
//     captured.
//
// Out of scope (per issue body): optimisation, golden-file updates.
// The committed baseline is regenerated by re-running this test and
// piping `BUILD/tests/control/baseline_gate_counts.txt` over
// `tests/control/baseline_gate_counts.txt` once the refactor lands.

#define STURM_BACKEND_ENABLED 1
#include "sturm/detail/lib/add_mod_dsl.hpp"
#include "sturm/detail/lib/mul_mod_dsl.hpp"
#include "sturm/detail/lib/pow_mod_dsl.hpp"
#include "sturm/detail/qtypes/bit_proxy.hpp"
#include "sturm/qtypes/qbool.hpp"
#include "sturm/control/when.hpp"
#include "sturm/core/context.hpp"
#include "sturm/core/core.h"
#include "sturm/core/qubit_pool.hpp"
#include "sturm/backend/orkan_bridge.hpp"

#include <cassert>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>
#include <vector>

// ── BackendContext harness (COUNT_ONLY mode, no simulator state) ────────────
// COUNT_ONLY only increments ctx.gate_count on each execute_gate; no Orkan
// state is required.  We still set max_qubits high enough to clear the cap
// check inside the lib primitives.
struct CountCtx {
    sturm_backend_context_t* ctx;
    sturm_backend_context_t* prev;
    explicit CountCtx(uint32_t max_q = 1024u) {
        ctx = sturm_backend_create(STURM_MODE_COUNT_ONLY, max_q);
        assert(ctx);
        prev = sturm_get_thread_context();
        sturm_set_thread_context(ctx);
    }
    ~CountCtx() {
        sturm_set_thread_context(prev);
        sturm_backend_destroy(ctx);
    }
};

// ── Register builder ────────────────────────────────────────────────────────
// Allocates `n` qubits from the pool, builds n owning qbool views with
// super_mask = 1 (so classicality specialisation does NOT skip dispatch),
// and projects them through BitProxy so the lib_*_mod_dsl templates accept
// them.  Owners and indices live in the caller's vectors so they outlive
// the BitProxy array.
struct Reg {
    std::vector<int>              qi;
    std::vector<sturm::qbool>     owners;   // non-owning, mask=1
    std::vector<sturm::BitProxy>  bits;
};

static Reg make_reg(std::size_t n) {
    Reg r;
    r.qi.resize(n);
    r.owners.resize(n);
    r.bits.resize(n);
    for (std::size_t i = 0; i < n; ++i) {
        r.qi[i]    = sturm::QubitPool::instance().allocate();
        r.owners[i] = sturm::qbool::make_non_owning(
            r.qi[i], /*val=*/0, /*mask=*/1ULL);
        r.bits[i]  = sturm::BitProxy(r.owners[i]);
    }
    return r;
}

static void release_reg(Reg& r) {
    // LIFO release.
    for (std::size_t i = r.qi.size(); i-- > 0;) {
        sturm::QubitPool::instance().release(r.qi[i]);
    }
    r.qi.clear();
    r.owners.clear();
    r.bits.clear();
}

// ── Per-primitive measurement entry points ─────────────────────────────────

// Returns the number of execute_gate calls emitted by lib_add_mod_dsl at
// width n.  When `wrap_in_when` is true the entire call site sits inside
// a `WHEN(c)` whose control is a freshly-allocated superposed qbool.
static uint64_t measure_add_mod(std::size_t n, bool wrap_in_when) {
    sturm::QubitPool::instance().reset_for_testing();
    CountCtx cc;
    Reg a = make_reg(n);
    Reg b = make_reg(n);
    Reg nm = make_reg(n);
    Reg r = make_reg(n);

    // Optional WHEN(c) wrapper.  Build the control qbool BEFORE we read
    // the pre-call gate count so the prepare gate emitted by the
    // probabilistic constructor (if any) doesn't pollute the delta.
    sturm::qbool c;
    int c_idx = -1;
    if (wrap_in_when) {
        c_idx = sturm::QubitPool::instance().allocate();
        c     = sturm::qbool::make_non_owning(c_idx, /*val=*/0, /*mask=*/1ULL);
    }

    const uint64_t before = sturm_gate_count(cc.ctx);
    if (wrap_in_when) {
        WHEN(c) {
            sturm::lib_add_mod_dsl<sturm::BitProxy>(
                a.bits.data(), b.bits.data(),
                nm.bits.data(), n, r.bits.data());
        }
    } else {
        sturm::lib_add_mod_dsl<sturm::BitProxy>(
            a.bits.data(), b.bits.data(),
            nm.bits.data(), n, r.bits.data());
    }
    const uint64_t after = sturm_gate_count(cc.ctx);

    if (wrap_in_when) sturm::QubitPool::instance().release(c_idx);
    release_reg(r); release_reg(nm); release_reg(b); release_reg(a);
    return after - before;
}

